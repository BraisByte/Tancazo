export function cloneMap(id = 'citadel') {
  const source = typeof id === 'object' && id?.rows ? id : MAPS[id] || MAPS.citadel;
  return {
    id: source.id || 'custom',
    name: source.name || 'Campo personalizado',
    width: source.rows[0].length,
    height: source.rows.length,
    tiles: source.rows.map((row) => [...row]),
    playerSpawns: source.playerSpawns.map((point) => [...point]),
    enemySpawns: source.enemySpawns.map((point) => [...point]),
    brickMasks: Object.fromEntries(source.rows.flatMap((row, rowIndex) => [...row].map((tile, colIndex) => tile === TILE.BRICK ? [`${rowIndex}:${colIndex}`, 15] : null).filter(Boolean))),
  };
}
